"""Export analysis results as a formatted Markdown file."""
from __future__ import annotations

import logging
from datetime import datetime

from pipeline.schema import AnalysisResult

logger = logging.getLogger(__name__)


def export_markdown(result: AnalysisResult) -> str:
    """Render *result* as a self-contained Markdown research note.

    Args:
        result: Complete analysis result.

    Returns:
        Formatted Markdown string with metrics table, insights, and
        inline ``[p.N]`` citations.
    """
    try:
        lines: list[str] = []
        meta = result.metadata

        # Title
        lines.append(f"# {meta.company_name} — Annual Report Analysis ({meta.fiscal_year})")
        lines.append("")

        # Metadata
        lines.append("## Report Metadata")
        lines.append(f"- **Company:** {meta.company_name}")
        lines.append(f"- **Fiscal Year:** {meta.fiscal_year}")
        lines.append(f"- **Source:** {meta.source_url or 'Manual upload'}")
        lines.append(f"- **Total Pages:** {meta.total_pages or 'N/A'}")
        lines.append(f"- **Analysed at:** {meta.discovered_at.strftime('%Y-%m-%d %H:%M')}")
        lines.append(f"- **Analysis Version:** {result.analysis_version}")
        lines.append("")

        # Financial Metrics
        lines.append("## Financial Metrics")
        if result.financial_data and result.financial_data.metrics:
            def _fmt(v: float | None) -> str:
                if v is None:
                    return "—"
                if v == int(v):
                    return f"{int(v):,}"
                return f"{v:,.2f}"

            lines.append(
                "| Metric | CY Consolidated | CY Standalone "
                "| PY Consolidated | PY Standalone | Unit | Page |"
            )
            lines.append("|---|---|---|---|---|---|---|")
            for m in result.financial_data.metrics:
                lines.append(
                    f"| {m.name} "
                    f"| {_fmt(m.current_year_consolidated)} "
                    f"| {_fmt(m.current_year_standalone)} "
                    f"| {_fmt(m.previous_year_consolidated)} "
                    f"| {_fmt(m.previous_year_standalone)} "
                    f"| {m.unit} "
                    f"| {f'[p.{m.page_number}]' if m.page_number else '—'} |"
                )
        else:
            lines.append("_No financial metrics extracted._")
        lines.append("")

        # Business Insights
        lines.append("## Business Insights")
        if result.insights and result.insights.insights:
            # Group by category
            by_cat: dict[str, list[str]] = {}
            for ins in result.insights.insights:
                by_cat.setdefault(ins.category, []).append(ins.content)

            for cat, items in by_cat.items():
                lines.append(f"### {cat}")
                for item in items:
                    lines.append(f"- {item}")
                lines.append("")
        else:
            lines.append("_No insights generated._")
        lines.append("")



        # Footer
        lines.append("---")
        lines.append(
            f"*Generated by Annual Report Analyzer v{result.analysis_version} "
            f"on {datetime.now().strftime('%Y-%m-%d %H:%M')}*"
        )

        md = "\n".join(lines)
        logger.info("Markdown export: %d lines, %d bytes", len(lines), len(md))
        return md

    except Exception:
        logger.exception("Error exporting to Markdown")
        raise
