"""RAG engine: embedding, FAISS index build/load, query rewriting, retrieval."""
from __future__ import annotations

import logging
import re
from typing import Any

import faiss
import numpy as np
import openai

from pipeline.schema import ChatMessage, DocumentChunk

logger = logging.getLogger(__name__)

__version__ = "1.0.0"


class RAGEngine:
    """Retrieval-Augmented Generation over a single annual report.

    Embeddings are produced by a local CPU-only llama-server on port 8081.
    Answers are generated by the GPU-resident LLM on port 8080.  Both
    speak the OpenAI-compatible API.

    The FAISS index (``IndexFlatIP`` with L2-normalised vectors for cosine
    similarity) is built once per report and cached to disk.
    """

    def __init__(
        self,
        embedding_base_url: str = "http://localhost:8081",
        llm_base_url: str = "http://localhost:8080",
        cache: Any | None = None,
    ) -> None:
        self.embed_client = openai.AsyncOpenAI(
            base_url=f"{embedding_base_url}/v1", api_key="not-needed"
        )
        self.llm_client = openai.AsyncOpenAI(
            base_url=f"{llm_base_url}/v1", api_key="not-needed"
        )
        self.cache = cache
        self.index: faiss.Index | None = None
        self.chunks: list[DocumentChunk] = []

    # ------------------------------------------------------------------
    # Index build / load
    # ------------------------------------------------------------------

    async def build_index(
        self, chunks: list[DocumentChunk], company_id: str, progress_callback=None
    ) -> None:
        """Embed all chunks and build a FAISS inner-product index.

        Args:
            chunks: Document chunks to embed.
            company_id: Slugified identifier for cache persistence.
            progress_callback: Optional callable for reporting progress.
        """
        logger.info(
            "Building FAISS index for '%s' with %d chunks", company_id, len(chunks)
        )

        texts = [c.text for c in chunks]
        embeddings = await self.embed_texts(texts, progress_callback=progress_callback)

        if not embeddings:
            logger.error("No embeddings returned – cannot build index")
            return

        for chunk, emb in zip(chunks, embeddings):
            chunk.embedding = emb

        self.chunks = chunks
        dim = len(embeddings[0])
        self.index = faiss.IndexFlatIP(dim)

        vectors = np.array(embeddings, dtype=np.float32)
        faiss.normalize_L2(vectors)
        self.index.add(vectors)

        logger.info(
            "FAISS index ready: %d vectors, dim=%d", self.index.ntotal, dim
        )

        # Persist via cache
        if self.cache is not None:
            try:
                self.cache.save_faiss_index(company_id, self.index)
                self.cache.save_chunks(company_id, chunks)
            except Exception:
                logger.exception("Failed to persist index/chunks to cache")

    def load_index(self, company_id: str) -> bool:
        """Try to load a previously built index from cache.

        Returns:
            ``True`` if the index was loaded successfully.
        """
        if self.cache is None:
            return False

        try:
            index = self.cache.load_faiss_index(company_id)
            chunks = self.cache.load_chunks(company_id)
            if index is not None and chunks is not None:
                self.index = index
                self.chunks = chunks
                logger.info(
                    "Loaded cached index for '%s' (%d vectors, %d chunks)",
                    company_id,
                    self.index.ntotal,
                    len(self.chunks),
                )
                return True
        except Exception:
            logger.exception("Failed to load cached index for '%s'", company_id)

        return False

    # ------------------------------------------------------------------
    # Embedding
    # ------------------------------------------------------------------

    async def embed_texts(
        self, texts: list[str], batch_size: int = 32, progress_callback=None
    ) -> list[list[float]]:
        """Embed a list of texts via the local embedding server.

        Args:
            texts: Strings to embed.
            batch_size: Number of texts per API call.
            progress_callback: Optional callable for reporting progress.

        Returns:
            List of embedding vectors (same order as *texts*).
        """
        logger.info("Embedding %d texts in batches of %d", len(texts), batch_size)
        all_embeddings: list[list[float]] = []
        total_texts = len(texts)

        for i in range(0, total_texts, batch_size):
            batch = texts[i : i + batch_size]
            try:
                response = await self.embed_client.embeddings.create(
                    model="qwen-embedding",
                    input=batch,
                )
                batch_embs = [d.embedding for d in response.data]
                all_embeddings.extend(batch_embs)
                logger.debug("Embedded batch %d/%d", i // batch_size + 1,
                             (total_texts + batch_size - 1) // batch_size)
            except Exception:
                logger.exception("Error embedding batch starting at index %d", i)
                # Pad with zeros so indices stay aligned.
                dummy_dim = len(all_embeddings[0]) if all_embeddings else 1024
                all_embeddings.extend([[0.0] * dummy_dim] * len(batch))

            if progress_callback:
                progress_callback(min(i + batch_size, total_texts), total_texts)

        return all_embeddings

    # ------------------------------------------------------------------
    # Search
    # ------------------------------------------------------------------

    async def search(self, query: str, top_k: int = 10, threshold: float = 0.3) -> list[tuple[DocumentChunk, float]]:
        """Embed *query* and return the top-k chunks that meet the threshold along with their confidence scores."""
        from pipeline.model_manager import model_manager
        
        if self.index is None or self.index.ntotal == 0:
            logger.warning("Search called on empty or uninitialized index")
            return []

        logger.info("Searching for: '%s'", query)
        
        model_manager.require_embedding()
        query_emb = await self.embed_texts([query])
        if not query_emb:
            return []

        vec = np.array(query_emb, dtype=np.float32)
        faiss.normalize_L2(vec)

        k = min(top_k, self.index.ntotal)
        distances, indices = self.index.search(vec, k)

        results = [
            (self.chunks[idx], float(dist))
            for idx, dist in zip(indices[0], distances[0])
            if idx != -1 and dist >= threshold
        ]
        logger.info("Retrieved %d chunks (above threshold %.2f) for query", len(results), threshold)
        return results

    # ------------------------------------------------------------------
    # Full RAG answer using Tool Calling
    # ------------------------------------------------------------------

    async def answer_question(
        self,
        question: str,
        chat_history: list[ChatMessage] | None = None,
        stream_callback=None,
        status_callback=None
    ) -> tuple[str, list[int], dict]:
        """Full Agentic RAG pipeline using LLM Tool Calling."""
        from pipeline.model_manager import model_manager
        import json
        import time

        # 1. Start LLM to evaluate query
        model_manager.require_llm()

        tools = [{
            "type": "function",
            "function": {
                "name": "search_annual_report",
                "description": "Search the annual report vector database for financial data, subsidiary info, or specific facts. Use this tool whenever the user asks for specific data or facts about the company.",
                "parameters": {
                    "type": "object",
                    "properties": {
                        "query": {
                            "type": "string",
                            "description": "The highly specific standalone search query to look up in the database."
                        }
                    },
                    "required": ["query"]
                }
            }
        }]

        system_msg = (
            "You are a helpful AI assistant answering questions about an annual report. "
            "If the user asks a conversational question, answer naturally. "
            "If the user asks about facts, figures, or details regarding the company, YOU MUST CALL the `search_annual_report` tool to find the information."
        )

        messages: list[dict] = [{"role": "system", "content": system_msg}]
        if chat_history:
            for m in chat_history[-5:]:
                messages.append({"role": m.role, "content": m.content})
        messages.append({"role": "user", "content": question})

        start_time = time.perf_counter()
        
        logger.info("Sending query to LLM for intent / tool decision")
        resp = await self.llm_client.chat.completions.create(
            model="qwen",
            messages=messages,
            tools=tools,
            temperature=0.1,
            max_tokens=2048,
            stream=True,
            stream_options={"include_usage": True},
            extra_body={"chat_template_kwargs": {"enable_thinking": False}}
        )

        answer = ""
        usage_stats = None
        is_tool_call = False
        tool_call_id = ""
        tool_name = ""
        tool_args = ""
        cited = []

        # Process the first stream (which might just be conversational text, or a tool call)
        tool_calls_dict = {}
        
        async for chunk in resp:
            if not chunk.choices:
                if chunk.usage:
                    usage_stats = chunk.usage
                continue
                
            delta = chunk.choices[0].delta
            
            if delta.tool_calls:
                is_tool_call = True
                for tc in delta.tool_calls:
                    idx = tc.index
                    if idx not in tool_calls_dict:
                        tool_calls_dict[idx] = {"id": "", "name": "", "args": ""}
                        if status_callback:
                            status_callback({"type": "info", "content": f"\n\n--- Tool Call {idx+1} ---"})
                    if tc.id:
                        tool_calls_dict[idx]["id"] = tc.id
                    if tc.function and tc.function.name:
                        tool_calls_dict[idx]["name"] += tc.function.name
                        if status_callback:
                            status_callback({"type": "tool_name", "content": tc.function.name})
                    if tc.function and tc.function.arguments:
                        arg_chunk = tc.function.arguments
                        tool_calls_dict[idx]["args"] += arg_chunk
                        if status_callback:
                            status_callback({"type": "tool_stream", "content": arg_chunk})
            elif not is_tool_call and delta.content:
                content = delta.content
                answer += content
                if stream_callback:
                    stream_callback(content)

        # If it was a conversational answer (no tool call), we are done!
        if not is_tool_call:
            logger.info("LLM answered conversationally without RAG")
            if status_callback:
                status_callback({"type": "info", "content": "Answered directly (No RAG search needed)."})
                status_callback({"type": "complete"})
            
            end_time = time.perf_counter()
            total_time = end_time - start_time
            stats = {
                "total_time": total_time,
                "input_tokens": getattr(usage_stats, "prompt_tokens", 0) if usage_stats else 0,
                "output_tokens": getattr(usage_stats, "completion_tokens", 0) if usage_stats else 0,
            }
            stats["speed"] = stats["output_tokens"] / stats["total_time"] if stats["total_time"] > 0 else 0.0
            return answer, cited, stats

        # ---------------------------------------------------------
        # If the LLM decided to call the tool, execute all searches!
        # ---------------------------------------------------------
        # Append the assistant's request with all tool calls
        assistant_message = {
            "role": "assistant",
            "content": None,
            "tool_calls": []
        }
        for idx, tc_data in tool_calls_dict.items():
            assistant_message["tool_calls"].append({
                "id": tc_data["id"] if tc_data["id"] else f"call_{idx}",
                "type": "function",
                "function": {
                    "name": tc_data["name"],
                    "arguments": tc_data["args"]
                }
            })
        messages.append(assistant_message)
        
        # Execute each tool call
        for idx, tc_data in tool_calls_dict.items():
            tool_name = tc_data["name"]
            tool_args = tc_data["args"]
            tool_id = tc_data["id"] if tc_data["id"] else f"call_{idx}"
            
            logger.info("Executing tool %s: %s", tool_name, tool_args)
            
            try:
                args_dict = json.loads(tool_args)
                search_query = args_dict.get("query", question)
            except Exception:
                search_query = question

            if status_callback:
                status_callback({"type": "info", "content": f"\nExecuting vector search for: `{search_query}`"})

            model_manager.require_embedding()
            chunks_with_scores = await self.search(search_query)
            
            if chunks_with_scores:
                scores = [score for _, score in chunks_with_scores]
                max_conf = max(scores)
                min_conf = min(scores)
                if status_callback:
                    status_callback({"type": "info", "content": f"Found {len(chunks_with_scores)} document chunks (Max Confidence: {max_conf:.2f}, Min Confidence: {min_conf:.2f})."})
                tool_result = self._build_rag_prompt(search_query, chunks_with_scores)
            else:
                if status_callback:
                    status_callback({"type": "info", "content": "Found 0 relevant chunks."})
                tool_result = "I couldn't find any relevant information in the report."

            messages.append({
                "role": "tool",
                "tool_call_id": tool_id,
                "content": tool_result
            })
            
        if status_callback:
            status_callback({"type": "info", "content": "\nAll searches complete. Generating final answer..."})

        # 3. Swap back to LLM to generate the final answer based on tool outputs
        model_manager.require_llm()

        logger.info("Generating final answer from tool output")
        resp2 = await self.llm_client.chat.completions.create(
            model="qwen",
            messages=messages,
            temperature=0.2,
            max_tokens=2048,
            stream=True,
            stream_options={"include_usage": True},
            extra_body={"chat_template_kwargs": {"enable_thinking": False}}
        )

        answer = ""
        async for chunk in resp2:
            if not chunk.choices:
                if chunk.usage:
                    if usage_stats:
                        # Accumulate tokens across both LLM calls
                        usage_stats.prompt_tokens += chunk.usage.prompt_tokens
                        usage_stats.completion_tokens += chunk.usage.completion_tokens
                    else:
                        usage_stats = chunk.usage
                continue
                
            delta = chunk.choices[0].delta
            if delta.content:
                content = delta.content
                answer += content
                if stream_callback:
                    stream_callback(content)

        if not answer.strip():
            answer = "I was unable to generate an answer from the report."
            if stream_callback:
                stream_callback(answer)

        cited = sorted({int(m) for m in re.findall(r"\[p\.(\d+)\]", answer)})
        logger.info("Answer generated, %d pages cited", len(cited))

        end_time = time.perf_counter()
        total_time = end_time - start_time

        stats = {
            "total_time": total_time,
            "input_tokens": getattr(usage_stats, "prompt_tokens", 0) if usage_stats else 0,
            "output_tokens": getattr(usage_stats, "completion_tokens", 0) if usage_stats else 0,
        }
        stats["speed"] = stats["output_tokens"] / stats["total_time"] if stats["total_time"] > 0 else 0.0

        return answer, cited, stats

    # ------------------------------------------------------------------
    # Prompt builder
    # ------------------------------------------------------------------

    def _build_rag_prompt(
        self, question: str, chunks_with_scores: list[tuple[DocumentChunk, float]]
    ) -> str:
        parts: list[str] = []
        for i, (c, score) in enumerate(chunks_with_scores, 1):
            pages = ", ".join(str(p) for p in c.page_numbers)
            parts.append(f"--- Chunk {i} (Pages: {pages}, Relevance: {score:.2f}) ---\n{c.text}")

        excerpts = "\n\n".join(parts)
        return (
            "Answer the following question using ONLY the provided excerpts "
            "from the annual report.\n\n"
            "Rules:\n"
            "1. Use ONLY the provided excerpts. If they don't contain enough "
            "information, say so explicitly.\n"
            "2. Do NOT use outside knowledge.\n"
            "3. Cite page numbers as [p.N] for every claim.\n\n"
            f"Excerpts:\n{excerpts}\n\n"
            f"Question: {question}\n"
            "Answer:"
        )
